#!/usr/bin/env python3
"""Deterministic empirical characterization of the 600 real GitHub PR traces."""
from __future__ import annotations

import hashlib
import json
from collections import Counter
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Set

REPO_ROOT = Path(__file__).resolve().parent.parent
TRACES_DIR = REPO_ROOT / "data" / "traces"

FILES = [
    ("kubernetes/kubernetes", TRACES_DIR / "kubernetes_kubernetes.json"),
    ("microsoft/TypeScript", TRACES_DIR / "microsoft_TypeScript.json"),
    ("vercel/next.js", TRACES_DIR / "vercel_next_js.json"),
]


def _sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _mod2(path: str) -> str:
    parts = path.split("/")[:-1][:2]
    return "/".join(parts) if parts else "."


def _gini(counts: List[int]) -> float:
    if not counts:
        return 0.0
    xs = sorted(counts)
    n = len(xs)
    total = sum(xs)
    if total == 0:
        return 0.0
    cum = sum((i + 1) * x for i, x in enumerate(xs))
    return (2.0 * cum) / (n * total) - (n + 1.0) / n


def _pct(vals: List[float], q: float) -> float:
    if not vals:
        return 0.0
    s = sorted(vals)
    pos = (len(s) - 1) * q
    lo = int(pos)
    hi = min(lo + 1, len(s) - 1)
    return s[lo] + (pos - lo) * (s[hi] - s[lo])


def analyze_repo(label: str, path: Path) -> Dict[str, Any]:
    rows = json.loads(path.read_text(encoding="utf-8"))
    rows.sort(key=lambda r: (r["merged_at"], r["number"]))
    times = [datetime.fromisoformat(r["merged_at"].replace("Z", "+00:00")) for r in rows]
    span_hr = (times[-1] - times[0]).total_seconds() / 3600.0 if len(times) > 1 else 0.0
    gaps_min = [(times[i] - times[i - 1]).total_seconds() / 60.0 for i in range(1, len(times))]

    file_counts: Counter = Counter()
    churns: List[float] = []
    files_per_pr: List[int] = []
    truncated = 0
    mod_sets: List[Set[str]] = []
    for r in rows:
        fs = r.get("files", [])
        if r.get("changed_files_count", len(fs)) > len(fs):
            truncated += 1
        files_per_pr.append(len(fs))
        churns.append(float(r.get("additions", 0) + r.get("deletions", 0)))
        for f in fs:
            file_counts[f] += 1
        mod_sets.append({_mod2(f) for f in fs})

    # Consecutive K=8 FIFO window 2-level-module overlap rate
    win_k = 8
    windows = max(1, len(rows) - win_k + 1)
    overlap_windows = 0
    for i in range(windows):
        seen: Set[str] = set()
        hit = False
        for ms in mod_sets[i : i + win_k]:
            if not seen.isdisjoint(ms):
                hit = True
                break
            seen.update(ms)
        if hit:
            overlap_windows += 1

    # Greedy graph-disjoint batchability in rolling windows of 16 PRs (batch size >= 4)
    roll = 16
    packable_windows = 0
    roll_count = max(1, len(rows) - roll + 1)
    for i in range(roll_count):
        used: Set[str] = set()
        packed = 0
        for ms in mod_sets[i : i + roll]:
            if used.isdisjoint(ms):
                used.update(ms)
                packed += 1
        if packed >= 4:
            packable_windows += 1

    return {
        "repo": label,
        "sha256": _sha256(path),
        "prs": len(rows),
        "span_hours": round(span_hr, 2),
        "median_gap_min": round(_pct(gaps_min, 0.50), 2),
        "p95_gap_min": round(_pct(gaps_min, 0.95), 2),
        "unique_files": len(file_counts),
        "mean_files_per_pr": round(sum(files_per_pr) / max(1, len(files_per_pr)), 2),
        "median_churn_loc": round(_pct(churns, 0.50), 1),
        "p95_churn_loc": round(_pct(churns, 0.95), 1),
        "truncated_file_list_prs": truncated,
        "hotspot_gini": round(_gini(list(file_counts.values())), 3),
        "fifo_k8_module_overlap_rate": round(overlap_windows / windows, 4),
        "disjoint_batch4_feasibility_rate": round(packable_windows / roll_count, 4),
    }


def main() -> None:
    stats = [analyze_repo(label, p) for label, p in FILES]
    out = {
        "total_prs": sum(s["prs"] for s in stats),
        "repositories": stats,
    }
    (REPO_ROOT / "results" / "trace_stats.json").write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")

    tex = [
        "% AUTO-GENERATED BY eval/analyze_traces.py — DO NOT EDIT",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Empirical Characteristics of the 600 Real Merged GitHub PR Traces.}",
        "\\label{tab:trace_summary}",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "\\textbf{Repository} & \\textbf{PRs} & \\textbf{Uniq.} & \\textbf{Gini} & \\textbf{FIFO-8} & \\textbf{Disj.-4} \\\\",
        " &  & \\textbf{Files} &  & \\textbf{Overlap} & \\textbf{Feasib.} \\\\",
        "\\midrule",
    ]
    for s in stats:
        short = s["repo"].split("/")[-1].replace("_", r"\_")
        tex.append(
            f"\\texttt{{{short}}} & {s['prs']} & {s['unique_files']} & {s['hotspot_gini']:.2f} & "
            f"{s['fifo_k8_module_overlap_rate']*100:.1f}\\% & {s['disjoint_batch4_feasibility_rate']*100:.1f}\\% \\\\"
        )
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    tex_path = REPO_ROOT / "paper" / "generated" / "tables" / "trace_summary.tex"
    tex_path.parent.mkdir(parents=True, exist_ok=True)
    tex_path.write_text("\n".join(tex) + "\n", encoding="utf-8")
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
